// ── Generate image URL map from manifest ──────────────────────
// Reads image-manifest.json, extracts all content image paths,
// matches them against manifest entries, and generates
// lib/image-url-map.ts with local-path → external-URL mappings.
//
// Run: node scripts/generate-url-map.js

const fs = require("fs");
const path = require("path");

const manifest = require("../image-manifest.json");
const contentDir = path.join(__dirname, "..", "lib", "content");

// Build manifest lookup: articleDir (from content) → manifest key
const manifestKeys = Object.keys(manifest.articles);
const dirToKey = new Map();
for (const dir of manifestKeys) {
  dirToKey.set(dir, dir); // exact match
}

// Build url map
const urlMap = {};  // localPath → externalUrl

// Scan all content files for image paths
const contentFiles = fs.readdirSync(contentDir).filter((f) => f.endsWith(".ts"));

for (const file of contentFiles) {
  const content = fs.readFileSync(path.join(contentDir, file), "utf8");
  // Match all [[PHOTO:orientation|/images/experiences/...|...]] markers
  const photoRegex = /\[\[PHOTO:(?:landscape|portrait|square|wide|full-width)\|(\/images\/experiences\/[^|]+)\|/g;
  let match;
  while ((match = photoRegex.exec(content)) !== null) {
    const localPath = match[1];
    // Extract article directory and filename
    const pathMatch = localPath.match(/^\/images\/experiences\/([\w-]+)\/(.+)$/);
    if (!pathMatch) continue;

    const articleDir = pathMatch[1];
    const filename = pathMatch[2];

    // Find manifest key for this dir
    let manifestKey = dirToKey.get(articleDir);
    if (!manifestKey) {
      // Try number prefix match
      const prefix = articleDir.match(/^(\d+)/)?.[1];
      if (prefix) {
        const candidates = manifestKeys.filter((k) => k.startsWith(prefix + "-"));
        if (candidates.length === 1) manifestKey = candidates[0];
      }
    }

    if (!manifestKey || !manifest.articles[manifestKey]) continue;

    // Find image in manifest
    const article = manifest.articles[manifestKey];
    const image = article.images?.find((img) => img.filename === filename);
    if (image?.originalUrl && image.usageStatus === "LIVE_VIA_URL") {
      urlMap[localPath] = image.originalUrl;
    }
  }
}

// Write the map file
const outputPath = path.join(__dirname, "..", "lib", "image-url-map.ts");
const entries = Object.entries(urlMap);
const output = [
  "// Generated by scripts/generate-url-map.js — DO NOT EDIT",
  "// Maps local /images/experiences/... paths to external Wikimedia/Unsplash URLs",
  "// from image-manifest.json integration data.",
  `// ${entries.length} images resolved. Regenerate: node scripts/generate-url-map.js`,
  "",
  "/** Maps local image path → external URL (Wikimedia Commons, Unsplash, etc.) */",
  `const urlMap: Record<string, string> = {`,
  ...entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  "};",
  "",
  "/**",
  " * Resolve a local image path to its external URL.",
  " * Returns the external URL if found, undefined otherwise.",
  " */",
  "export function resolveImageUrl(localPath: string): string | undefined {",
  "  return urlMap[localPath];",
  "}",
  "",
  "/** Check whether a local path has a known external URL */",
  "export function hasExternalUrl(localPath: string): boolean {",
  "  return localPath in urlMap;",
  "}",
  "",
  "export default urlMap;",
  "",
].join("\n");

fs.writeFileSync(outputPath, output, "utf8");
console.log(`Generated lib/image-url-map.ts with ${entries.length} URL mappings.`);
console.log("Entries:");
entries.forEach(([k, v]) => console.log(`  ${k} → ${v.substring(0, 80)}...`));
